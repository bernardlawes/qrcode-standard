// Copies the pinned browser builds of our dependencies into public/vendor.
// The vendored files are committed so the app needs no build step and no CDN.
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');
const out = join(root, 'public', 'vendor');

const files = [
  ['lean-qr/index.mjs', 'lean-qr/index.mjs'],
  ['lean-qr/extras/svg.mjs', 'lean-qr/extras/svg.mjs'],
  ['lean-qr/extras/errors.mjs', 'lean-qr/extras/errors.mjs'],
  ['lean-qr/LICENSE', 'lean-qr/LICENSE'],
  // reader/index.js imports ../share.js, so keep that relative layout
  ['zxing-wasm/dist/es/reader/index.js', 'zxing-wasm/reader/index.js'],
  ['zxing-wasm/dist/es/share.js', 'zxing-wasm/share.js'],
  ['zxing-wasm/dist/reader/zxing_reader.wasm', 'zxing-wasm/reader/zxing_reader.wasm'],
  ['zxing-wasm/LICENSE', 'zxing-wasm/LICENSE'],
];

await rm(out, { recursive: true, force: true });
for (const [from, to] of files) {
  await mkdir(dirname(join(out, to)), { recursive: true });
  await cp(join(nm, from), join(out, to));
}

const versions = [];
for (const pkg of ['lean-qr', 'zxing-wasm']) {
  const { version } = JSON.parse(await readFile(join(nm, pkg, 'package.json'), 'utf8'));
  versions.push(`- ${pkg} ${version}`);
}
await writeFile(join(out, 'VENDOR.md'),
  `# Vendored libraries\n\nGenerated by \`npm run vendor\` — do not edit by hand.\n\n${versions.join('\n')}\n`);
console.log(`Vendored ${files.length} files:\n${versions.join('\n')}`);
