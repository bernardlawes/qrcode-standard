// Propagates public/src/config.js to the files that can't import it:
// manifest.json, page <title>s / meta tags, the service worker's
// version + precache list, and robots.txt / sitemap.xml (from ORIGIN).
//   npm run sync           write changes
//   node tools/sync.mjs --check   exit 1 if anything is out of date (used by tests)
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as config from '../public/src/config.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(root, 'public');

// Never precached: host config, the SW itself, docs/licences, crawler files.
const EXCLUDE = [/^\/_headers$/, /^\/sw\.js$/, /\.md$/, /LICENSE$/, /^\/robots\.txt$/, /^\/sitemap\.xml$/];

// Public pages listed for search engines, at their clean URLs.
const PAGES = ['/', '/generate', '/scan'];

// Cloudflare Pages serves pages at clean URLs and 308-redirects /x.html → /x
// (and /index.html → /). Precache the URLs it actually serves.
export const cleanUrl = (f) => f.replace(/(^|\/)index\.html$/, '$1').replace(/\.html$/, '');

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else files.push('/' + relative(PUBLIC, full).split(sep).join('/'));
  }
  return files;
}

export function manifest() {
  return JSON.stringify({
    name: config.APP_NAME,
    short_name: config.SHORT_NAME,
    description: config.APP_DESCRIPTION,
    id: '/',
    start_url: '/',
    scope: '/',
    display: 'standalone',
    background_color: config.BACKGROUND_COLOR,
    theme_color: config.THEME_COLOR,
    icons: [
      { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png' },
      { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      { src: '/icons/icon.svg', sizes: 'any', type: 'image/svg+xml' },
    ],
  }, null, 2) + '\n';
}

function html(src) {
  const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
  return src
    .replace(/<title>(?:(.+?) · )?[^<]*<\/title>/, (_, page) => `<title>${page ? `${page} · ` : ''}${esc(config.APP_NAME)}</title>`)
    .replace(/(<[^>]*data-app-name[^>]*>)[^<]*</g, `$1${esc(config.APP_NAME)}<`)
    .replace(/(<[^>]*data-app-short[^>]*>)[^<]*</g, `$1${esc(config.SHORT_NAME)}<`)
    .replace(/(<meta name="description" content=")[^"]*"/, `$1${esc(config.APP_DESCRIPTION)}"`)
    .replace(/(<meta name="theme-color" content=")[^"]*"/, `$1${esc(config.THEME_COLOR)}"`);
}

// The app is public and meant to be found: allow everything, point to the sitemap.
const robots = () => `User-agent: *\nAllow: /\n\nSitemap: ${config.ORIGIN}/sitemap.xml\n`;

const sitemap = () => '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  PAGES.map((p) => `  <url><loc>${config.ORIGIN}${p}</loc></url>\n`).join('') + '</urlset>\n';

async function serviceWorker(src) {
  // manifest.json is listed explicitly: it may not exist yet on the first sync
  const files = [...new Set([...await walk(PUBLIC), '/manifest.json'])]
    .filter((f) => !EXCLUDE.some((re) => re.test(f)))
    .map(cleanUrl);
  const list = [...new Set(files)].sort().map((f) => `  '${f}',`).join('\n');
  const block = `// <generated by tools/sync.mjs — do not edit by hand>\nconst VERSION = '${config.APP_VERSION}';\nconst PRECACHE = [\n${list}\n];\n// </generated>`;
  return src.replace(/\/\/ <generated[\s\S]*?\/\/ <\/generated>/, block);
}

/** Map of absolute path → expected content. */
export async function expectedOutputs() {
  const out = new Map();
  out.set(join(PUBLIC, 'manifest.json'), manifest());
  for (const page of ['index.html', 'generate.html', 'scan.html']) {
    out.set(join(PUBLIC, page), html(await readFile(join(PUBLIC, page), 'utf8')));
  }
  out.set(join(root, 'tools', 'admin', 'index.html'), html(await readFile(join(root, 'tools', 'admin', 'index.html'), 'utf8')));
  out.set(join(PUBLIC, 'robots.txt'), robots());
  out.set(join(PUBLIC, 'sitemap.xml'), sitemap());
  out.set(join(PUBLIC, 'sw.js'), await serviceWorker(await readFile(join(PUBLIC, 'sw.js'), 'utf8')));
  return out;
}

/** Paths whose current content differs from what sync would write. */
export async function stalePaths() {
  const stale = [];
  for (const [path, content] of await expectedOutputs()) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current?.replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) stale.push(relative(root, path));
  }
  return stale;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    const stale = await stalePaths();
    if (stale.length) {
      console.error(`Out of date (run npm run sync): ${stale.join(', ')}`);
      process.exit(1);
    }
    console.log('All generated files are up to date.');
  } else {
    for (const [path, content] of await expectedOutputs()) await writeFile(path, content);
    console.log(`Synced from config: ${config.APP_NAME} v${config.APP_VERSION}`);
  }
}
